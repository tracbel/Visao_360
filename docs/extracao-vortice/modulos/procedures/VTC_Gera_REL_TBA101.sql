    -- Cursor para inserir linha a linha
    DECLARE
        @EMPRESA NVARCHAR(120), @CEN NVARCHAR(60), @JD_QUOTE NVARCHAR(120),
        @TIPO_VENDA NVARCHAR(120), @TIPO_DE_EQUIPAMENTO NVARCHAR(120),
        @MARCA NVARCHAR(120), @MODELO NVARCHAR(200), @SEQPESSOA INT,
        @NOMERAZAO NVARCHAR(200), @CNPJCPF NVARCHAR(32),
        @LINHA_CREDITO NVARCHAR(120), @INST_FINANCEIRA NVARCHAR(120),
        @FINANC_CHASSI NVARCHAR(120), @ULT_RESULTADO NVARCHAR(400),
        @DTA_FATURAMENTO_D DATETIME, @NF_N NVARCHAR(60),
        @DTA_PED_D DATETIME, @DTA_PRENCH_FORM_D DATETIME,
        @VALOR_N DECIMAL(18,2), @DTA_ULT_ANDAMENTO_D DATETIME,
        @ULT_HISTORICO_L NVARCHAR(MAX), @PROCESSO_N INT, @CARTEIRA NVARCHAR(60),
        @CIDADE NVARCHAR(150), @DATA_PEDIDO_HIST_D DATETIME,
        @CAMPANHA NVARCHAR(150), @PROCESSODNA INT, @DTAPROVADO NVARCHAR(10);

    DECLARE cur CURSOR FAST_FORWARD FOR
        SELECT EMPRESA, CEN, JD_QUOTE, TIPO_VENDA, TIPO_DE_EQUIPAMENTO, MARCA, MODELO,
               SEQPESSOA, NOMERAZAO, CNPJCPF, LINHA_CREDITO, INST_FINANCEIRA, FINANC_CHASSI,
               ULT_RESULTADO, DTA_FATURAMENTO_D, NF_N, DTA_PED_D, DTA_PRENCH_FORM_D, VALOR_N,
               DTA_ULT_ANDAMENTO_D, ULT_HISTORICO_L, PROCESSO_N, CARTEIRA, CIDADE,
               DATA_PEDIDO_HIST_D, CAMPANHA, PROCESSODNA, DTAPROVADO
        FROM #Stage;

    OPEN cur;
    FETCH NEXT FROM cur INTO
        @EMPRESA, @CEN, @JD_QUOTE, @TIPO_VENDA, @TIPO_DE_EQUIPAMENTO, @MARCA, @MODELO,
        @SEQPESSOA, @NOMERAZAO, @CNPJCPF, @LINHA_CREDITO, @INST_FINANCEIRA, @FINANC_CHASSI,
        @ULT_RESULTADO, @DTA_FATURAMENTO_D, @NF_N, @DTA_PED_D, @DTA_PRENCH_FORM_D, @VALOR_N,
        @DTA_ULT_ANDAMENTO_D, @ULT_HISTORICO_L, @PROCESSO_N, @CARTEIRA, @CIDADE,
        @DATA_PEDIDO_HIST_D, @CAMPANHA, @PROCESSODNA, @DTAPROVADO;

    WHILE @@FETCH_STATUS = 0
    BEGIN
        INSERT INTO dbo.IMP_REL_TBA101
        (
            CODUSUARIO, EMPRESA, CEN, JD_QUOTE, TIPO_VENDA, TIPO_DE_EQUIPAMENTO, MARCA, MODELO,
            SEQPESSOA, NOMERAZAO, CNPJCPF, LINHA_CREDITO, INST_FINANCEIRA, FINANC_CHASSI,
            ULT_RESULTADO, DTA_FATURAMENTO_D, NF_N, DTA_PED_D, DTA_PRENCH_FORM_D, VALOR_N,
            DTA_ULT_ANDAMENTO_D, ULT_HISTORICO_L, PROCESSO_N, CARTEIRA, CIDADE,
            DATA_PEDIDO_HIST_D, CAMPANHA, PROCESSODNA, DTAPROVADO
        )
        VALUES
        (
            @CODUSUARIO, @EMPRESA, @CEN, @JD_QUOTE, @TIPO_VENDA, @TIPO_DE_EQUIPAMENTO, @MARCA, @MODELO,
            @SEQPESSOA, @NOMERAZAO, @CNPJCPF, @LINHA_CREDITO, @INST_FINANCEIRA, @FINANC_CHASSI,
            @ULT_RESULTADO, @DTA_FATURAMENTO_D, @NF_N, @DTA_PED_D, @DTA_PRENCH_FORM_D, @VALOR_N,
            @DTA_ULT_ANDAMENTO_D, @ULT_HISTORICO_L, @PROCESSO_N, @CARTEIRA, @CIDADE,
            @DATA_PEDIDO_HIST_D, @CAMPANHA, @PROCESSODNA, @DTAPROVADO
        );

        FETCH NEXT FROM cur INTO
            @EMPRESA, @CEN, @JD_QUOTE, @TIPO_VENDA, @TIPO_DE_EQUIPAMENTO, @MARCA, @MODELO,
            @SEQPESSOA, @NOMERAZAO, @CNPJCPF, @LINHA_CREDITO, @INST_FINANCEIRA, @FINANC_CHASSI,
            @ULT_RESULTADO, @DTA_FATURAMENTO_D, @NF_N, @DTA_PED_D, @DTA_PRENCH_FORM_D, @VALOR_N,
            @DTA_ULT_ANDAMENTO_D, @ULT_HISTORICO_L, @PROCESSO_N, @CARTEIRA, @CIDADE,
            @DATA_PEDIDO_HIST_D, @CAMPANHA, @PROCESSODNA, @DTAPROVADO;
    END

    CLOSE cur; DEALLOCATE cur;
END
