   Outras refs .....: IV_Q$ACOMPANH_VENDA_JDE, IV_Q$GESTAO_CREDITO, IV_Q$GESTAO_CREDITO_AMS, IV_Q$GESTAO_CREDITO_IMP
   Fonte: banco CRM (Vortice CRM / Tracbel) - extracao somente leitura
