   Escreve em tabela: nao
   Tabelas referidas: IV_PROCDADO, IV_PROCESSO, IV_PROCPERSP, IV_PROCSTATMONIT
   Fonte: banco CRM (Vortice CRM / Tracbel) - extracao somente leitura
