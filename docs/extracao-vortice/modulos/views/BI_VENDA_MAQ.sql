		GFI.VALOR_TOTAL				AS VDA_VALOR,
		AVM.ITENS_AMS		        AS VDA_MODELO,
		'John Deere'      			AS VDA_MARCA,
		CASE WHEN ISNULL( AVM.CHASSI_AMS___1, '')='' THEN '' ELSE AVM.CHASSI_AMS___1 + ' || ' END  + 
		CASE WHEN ISNULL( AVM.CHASSI_AMS___2, '')='' THEN '' ELSE AVM.CHASSI_AMS___2 + ' || ' END  + 
		CASE WHEN ISNULL( AVM.CHASSI_AMS___3, '')='' THEN '' ELSE AVM.CHASSI_AMS___3 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___4, '')='' THEN '' ELSE AVM.CHASSI_AMS___4 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___5, '')='' THEN '' ELSE AVM.CHASSI_AMS___5 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___6, '')='' THEN '' ELSE AVM.CHASSI_AMS___6 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___7, '')='' THEN '' ELSE AVM.CHASSI_AMS___7 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___8, '')='' THEN '' ELSE AVM.CHASSI_AMS___8 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___9, '')='' THEN '' ELSE AVM.CHASSI_AMS___9 + ' || ' END  +
		CASE WHEN ISNULL( AVM.CHASSI_AMS___10, '')='' THEN '' ELSE AVM.CHASSI_AMS___10 + ' || ' END  
		AS CHASSI,
		'AMS'		AS VDA_TIPO_MAQUINA,
		GFI.PROBABILIDADE			AS VDA_PROB_APROVACAO,
		CASE WHEN GFI.STATUS_PROCESSO='Autorizado' then 'SIM' else 'NÃO' END AS VDA_PAC_EMITIDO,
		( SELECT DTALOG FROM GE_LgTb 
			WHERE tb='IV_QUESTIONARIO' and KN1 = GFI.SEQQUESTIONARIO AND CODAPL = ' IVS1QST01' 
			  AND OBS LIKE '%Status Processo Financ de Em Analise, para Fatur Autorizado%' ) AS VDA_DATA_PAC,
		CASE WHEN ISNULL(GFI.NOTA_FISCAL, 0)<>0 THEN 'SIM' else 'NÃO' END AS VDA_FATURAMENTO_REALIZADO,
		GFI.FATURAMENTO_REALIZAD 	AS VDA_DATA_FATURAMENTO,
		NULL AS VDA_DATA_PREVISTA_FATURAMENTO,
		NULL AS VDA_MES_PREVISTO_FATURAMENTO,
		NULL AS VDA_ORIGEM_FATURAMENTO,
		NULL AS VDA_DIAS_PEDIDO_PAC,
		NULL AS VDA_DIAS_PAC_FATURAMENTO,
		NULL AS VDA_DIAS_PEDIDO_FATURAMENTO,
		(SELECT MAX(DTAREALIZACAO) 
		 FROM IV_HISTORICO 
		 WHERE PROCESSO = GFI.PROCESSO
		   AND RESULTADO IN ( 1286, 255, 2143, 2176 )) AS data_pedido_de_venda,
	   HIS.Descricao AS APROVACAO_GESTOR,
	   (SELECT Distinct 'Em aberto' FROM IV_AGENDA WHERE PROCESSO = GFI.PROCESSO AND ACAO = 528 AND REALIZADA='N' )
	   AS APROVACAO_GESTOR_AGD,
	   NULL AS FDD,
	   NULL AS PREVISAO_ENTREGA_PRE,
	   GFI.STATUS_ANALISE_BC AS STATUS_BC1,
	   GFI.STATUS_BC_2		 AS STATUS_BC2,
	   GFI.ANALISE_BC_3		 AS STATUS_BC3,

	   NULL					AS COTACAO,
	   NULL				 AS INFORMACAO_PREPARACA,
	   AVM.DATA_ENTREGA			AS DATA_ENTREGA,
	   AVM.TRANSPORTADORA		AS TRANSPORTADORA,
	   AVM.PREVISAO_ENTREGA_PRE AS PREVISAO_ENTREGA_PRE,
	   GFI.INSTITUICAO_FIINSTIT AS INST_SELECIONADA

FROM IV_Q$GESTAO_CREDITO_AMS GFI
JOIN IV_Q$GESTAO_PRODUTO___AMS AVM ON AVM.PROCESSO = GFI.PROCESSO AND AVM.FORMULARIO_NUMERO = GFI.FORMULARIO_NUMERO
LEFT JOIN (SELECT HH.PROCESSO, RR.DESCRICAO, 
           ROW_NUMBER() OVER (PARTITION BY HH.PROCESSO ORDER BY HH.DTAREALIZACAO DESC ) AS RANK
           FROM IV_HISTORICO HH, IV_RESULTADO RR
		   WHERE HH.ACAOGERADORA = 528
